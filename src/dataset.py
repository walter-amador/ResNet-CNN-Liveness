"""
PyTorch Dataset and DataLoader factory for the liveness detection pipeline.

The dataset reads from split CSVs generated by scripts/generate_splits.py.
Each CSV has columns: filepath (absolute path), label (0=spoof, 1=live).

Usage:
    train_loader, val_loader, test_loader = build_dataloaders(config)
"""

from __future__ import annotations

import random
from pathlib import Path
from typing import Callable, Optional

import pandas as pd
from PIL import Image
import torch
from torch.utils.data import Dataset, DataLoader

from src.config import Config


class LivenessDataset(Dataset):
    """Face liveness dataset backed by a split CSV.

    Args:
        csv_path         : Path to train.csv / val.csv / test.csv.
        transform        : torchvision transform applied to each PIL image.
        subset_fraction  : If < 1.0, randomly sample this fraction of the dataset.
                           Useful for fast local iteration.
        seed             : Random seed for subset sampling.
    """

    def __init__(
        self,
        csv_path: str | Path,
        transform: Optional[Callable] = None,
        subset_fraction: float = 1.0,
        seed: int = 42,
    ) -> None:
        self.transform = transform

        df = pd.read_csv(csv_path)
        if "filepath" not in df.columns or "label" not in df.columns:
            raise ValueError(
                f"CSV must have 'filepath' and 'label' columns. Got: {list(df.columns)}"
            )

        if subset_fraction < 1.0:
            n = max(1, int(len(df) * subset_fraction))
            df = df.sample(n=n, random_state=seed).reset_index(drop=True)

        self.filepaths: list[str] = df["filepath"].tolist()
        self.labels: list[int]    = df["label"].tolist()

    def __len__(self) -> int:
        return len(self.filepaths)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int]:
        img_path = self.filepaths[idx]
        label    = self.labels[idx]

        image = Image.open(img_path).convert("RGB")
        if self.transform is not None:
            image = self.transform(image)

        return image, label

    def class_counts(self) -> dict[int, int]:
        """Return {label: count} for class balance inspection."""
        from collections import Counter
        return dict(Counter(self.labels))


def build_dataloaders(
    config: Config,
    train_transform: Optional[Callable] = None,
    val_transform: Optional[Callable] = None,
) -> tuple[DataLoader, DataLoader, DataLoader]:
    """Create train, val, and test DataLoaders from the split CSVs.

    Args:
        config          : Experiment configuration.
        train_transform : Override for training augmentations (defaults to config-based).
        val_transform   : Override for val/test transforms (defaults to config-based).

    Returns:
        (train_loader, val_loader, test_loader)
    """
    from src.transforms import get_train_transforms, get_val_transforms

    splits_dir = config.splits_dir

    if train_transform is None:
        train_transform = get_train_transforms(config)
    if val_transform is None:
        val_transform = get_val_transforms(config)

    train_ds = LivenessDataset(
        splits_dir / "train.csv",
        transform=train_transform,
        subset_fraction=config.subset_fraction,
        seed=config.seed,
    )
    val_ds = LivenessDataset(
        splits_dir / "val.csv",
        transform=val_transform,
        subset_fraction=config.subset_fraction,
        seed=config.seed,
    )
    test_ds = LivenessDataset(
        splits_dir / "test.csv",
        transform=val_transform,
        subset_fraction=1.0,   # always evaluate on full test set
        seed=config.seed,
    )

    # pin_memory only helps with CUDA; persistent_workers needs num_workers > 0
    pin   = config.device == "cuda"
    pers  = config.num_workers > 0

    common = dict(
        num_workers=config.num_workers,
        pin_memory=pin,
        persistent_workers=pers,
    )

    train_loader = DataLoader(
        train_ds,
        batch_size=config.batch_size,
        shuffle=True,
        drop_last=True,   # avoid partial batches during training
        **common,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=config.batch_size,
        shuffle=False,
        **common,
    )
    test_loader = DataLoader(
        test_ds,
        batch_size=config.batch_size,
        shuffle=False,
        **common,
    )

    return train_loader, val_loader, test_loader
